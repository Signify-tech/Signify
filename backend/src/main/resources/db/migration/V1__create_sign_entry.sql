-- Vocabulary and media metadata for Signify.
-- Media files live on disk under SIGNIFY_MEDIA_DIR; only their relative path is stored here.
CREATE TABLE sign_entry (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term                VARCHAR(120) NOT NULL,
    normalized_term     VARCHAR(120) NOT NULL,
    category            VARCHAR(16)  NOT NULL,
    media_path          VARCHAR(255),
    media_type          VARCHAR(16),
    source              VARCHAR(255),
    license             VARCHAR(255),
    attribution         VARCHAR(500),
    verification_status VARCHAR(16)  NOT NULL DEFAULT 'UNVERIFIED',
    notes               VARCHAR(500),
    created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sign_entry_term UNIQUE (category, normalized_term),
    CONSTRAINT ck_sign_entry_category CHECK (category IN ('WORD', 'PHRASE', 'LETTER', 'DIGIT')),
    CONSTRAINT ck_sign_entry_media_type CHECK (media_type IS NULL OR media_type IN ('VIDEO', 'GIF', 'IMAGE')),
    CONSTRAINT ck_sign_entry_verification CHECK (verification_status IN ('VERIFIED', 'UNVERIFIED'))
);

CREATE INDEX idx_sign_entry_category ON sign_entry (category);
